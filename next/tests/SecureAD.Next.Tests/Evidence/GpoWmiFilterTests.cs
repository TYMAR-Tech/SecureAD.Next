    private sealed record Options
    {
        internal string? Reference { get; init; } = "[child.example.test;" + FilterId + ";0]";
        internal bool IncludeFilter { get; init; } = true;
        internal string StoredFilterId { get; init; } = FilterId;
        internal string FilterClass { get; init; } = "msWMI-Som";
        internal string? Definition { get; init; } = RecordedWrapper;
        internal bool DuplicatePolicy { get; init; }
        internal bool DuplicateFilter { get; init; }
    }

    private static string Build(Options options)
    {
        var directory = TempDirectories.Create("gpo-wmi-reader");
        var parent = new PartitionCoverage(Parent, NamingContextKind.Domain, "dc.example.test",
            ConnectionSecurityLevel.SignedAndSealed, options.DuplicatePolicy ? 3 : 2, 1, 0, [], false);
        var child = new PartitionCoverage(Child, NamingContextKind.Domain, "dc.child.example.test",
            ConnectionSecurityLevel.SignedAndSealed, options.IncludeFilter ? options.DuplicateFilter ? 2 : 1 : 0, 1, 0, [], false);
        using var writer = BundleWriter.Create(directory, Captured);
        writer.WriteCoverage(parent);
        writer.WriteCoverage(child);
        var policy = new List<EvidenceAttribute> { Text("objectClass", "groupPolicyContainer"), Text("displayName", "Invented policy") };
        if (options.Reference is not null) policy.Add(Text("gPCWQLFilter", options.Reference));
        writer.WriteObject(new(parent, PolicyDn, PolicyGuid, policy, Captured));
        if (options.DuplicatePolicy)
            writer.WriteObject(new(parent, PolicyDn, Guid.Parse("55555555-5555-5555-5555-555555555555"),
                [Text("objectClass", "groupPolicyContainer"), Text("gPCWQLFilter", "[child.example.test;" + FilterId + ";9]")], Captured));
        // Same identifier in another domain must never supply the selected child-domain definition.
        writer.WriteObject(new(parent, "CN=" + FilterId + ",CN=SOM,CN=WMIPolicy,CN=System," + Parent, Guid.NewGuid(),
            [Text("objectClass", "msWMI-Som"), Text("msWMI-ID", FilterId), Text("msWMI-Parm2", "unrelated unreadable query")], Captured));
        if (options.IncludeFilter)
        {
            var filter = new List<EvidenceAttribute>
            {
                Text("objectClass", options.FilterClass), Text("msWMI-ID", options.StoredFilterId),
                Text("msWMI-Name", "Invented server filter"),
            };
            if (options.Definition is not null) filter.Add(Text("msWMI-Parm2", options.Definition));
            writer.WriteObject(new(child, FilterDn, FilterGuid, filter, Captured));
            if (options.DuplicateFilter)
                writer.WriteObject(new(child, FilterDn, Guid.NewGuid(), filter, Captured));
        }
        writer.Complete(RunCoverage.Of(CoverageId.ForDomains("example.test", ["example.test", "child.example.test"]),
            [DomainCoverage.Read("example.test"), DomainCoverage.Read("child.example.test")],
            [
                ForestPartitionCoverage.Read("CN=Configuration," + Parent, NamingContextKind.Configuration),
                ForestPartitionCoverage.Read("CN=Schema,CN=Configuration," + Parent, NamingContextKind.Schema),
            ], SysvolCoverage.Of([])), Captured.AddMinutes(1));
        return directory;
    }

    private static EvidenceAttribute Text(string name, string value) =>
        new(name, StoredAttributeCompleteness.Complete, [EvidenceValue.OfText(value)]);

