        var thread = new Thread(() => error = Record.Exception(() =>
        {
            var initialized = InitializeApartment(IntPtr.Zero, 2);
            Assert.True(initialized >= 0);
            try
            {
                Assert.Equal(0, GetApartment(out var originalApartment, out _));
                Assert.True(originalApartment is 0 or 3);
                result = WindowsWqlParser.Read(Query, CancellationToken.None);
                Assert.Equal(0, GetApartment(out var apartment, out _));
