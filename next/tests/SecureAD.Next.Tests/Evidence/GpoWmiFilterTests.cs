        var selectedGuid = Guid.Parse("55555555-5555-5555-5555-555555555555");
        command.Parameters.AddWithValue("$guid", selectedGuid.ToString("D"));
        var rowId = Assert.IsType<long>(command.ExecuteScalar());
        var selected = reader.ReadObjectIdentity(PolicyDn)! with { ObjectId = rowId, ObjectGuid = selectedGuid };
        var read = reader.ReadGpoWmiFilter(selected, CancellationToken.None);
        Assert.Equal(selectedGuid, read.Policy.ObjectGuid);
        Assert.Equal(rowId, read.Policy.ObjectId);
        Assert.Equal(read.PolicyValues.ObjectGuid, read.Policy.ObjectGuid);
        Assert.Equal("9", read.Reference!.IgnoredFlags);
        Assert.True(read.Definition.IsSuccess);
    }

