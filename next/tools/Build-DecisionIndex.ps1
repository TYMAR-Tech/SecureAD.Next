#Requires -Version 7.0
# Windows PowerShell 5.1 reads UTF-8 files as Windows-1252, turning every em dash into three
# characters. This script writes documents, so running it under 5.1 would corrupt them silently.

# Generates docs/DECISIONS.md from the decision records themselves.
#
# The index is derived, never maintained. A hand-written summary of the records is a second copy
# of every decision, and this repository has already lost time to one: POINT-IN-TIME-REVIEW.md
# claimed sixty-nine production files when there were sixty-eight, and predated five records while
# opening with "read this first if you have been away".
#
# Run with -Check to verify the committed file matches what the records would produce, which is
# what DecisionIndexTests does.
param(
    [switch] $Check
)

$ErrorActionPreference = 'Stop'

$repositoryRoot = Join-Path $PSScriptRoot '..\..' | Resolve-Path
$decisions = Join-Path $repositoryRoot 'docs\decisions'
$indexPath = Join-Path $repositoryRoot 'docs\DECISIONS.md'

$records = Get-ChildItem (Join-Path $decisions '0*.md') | Sort-Object Name

if ($records.Count -eq 0) {
    throw "No decision records found under '$decisions'."
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Decisions')
$lines.Add('')
$lines.Add('**Generated by `next/tools/Build-DecisionIndex.ps1`. Do not edit.**')
$lines.Add('')
$lines.Add('Every decision this product has taken, newest last. The record itself is the reasoning;')
$lines.Add('this is only a way in. Regenerate rather than correct a line here.')
$lines.Add('')
$lines.Add('| # | Date | Status | Decision |')
$lines.Add('|---|---|---|---|')

foreach ($record in $records) {
    $head = Get-Content $record.FullName -TotalCount 20

    $title = ($head | Where-Object { $_ -match '^#\s' } | Select-Object -First 1) -replace '^#\s*', ''
    $date = ($head | Where-Object { $_ -match '^Date:' } | Select-Object -First 1) -replace '^Date:\s*', ''
    $status = ($head | Where-Object { $_ -match '^Status:' } | Select-Object -First 1) -replace '^Status:\s*', ''

    if ([string]::IsNullOrWhiteSpace($title)) { throw "$($record.Name) has no '# ' title." }
    if ([string]::IsNullOrWhiteSpace($date)) { throw "$($record.Name) has no 'Date:' line." }
    if ([string]::IsNullOrWhiteSpace($status)) { throw "$($record.Name) has no 'Status:' line." }

    $number = $record.BaseName.Substring(0, 4)

    # The title repeats the number; the table has a column for it.
    $subject = ($title -replace "^$number\s*[-\u2013\u2014]\s*", '').Trim()

    # A status can run to several sentences where a record was corrected in place. Only the verdict
    # belongs here - Accepted, Proposed, Superseded by NNNN - and the qualification stays in the
    # record, marked so a reader knows to go and look. Links are flattened to their number because
    # a relative link copied out of a record does not resolve from this file.
    $verdict = $status -replace '\[([^\]]+)\]\([^)]*\)', '$1'
    $verdict = ($verdict -split '[.;,]', 2)[0].Trim()
    $qualified = if ($status.TrimEnd('.').Length -gt $verdict.Length) { ' *(see record)*' } else { '' }

    # Relative to docs/, which is where this file is written.
    $link = "decisions/$($record.Name)"
    $lines.Add("| [$number]($link) | $date | $verdict$qualified | $subject |")
}

$lines.Add('')

$generated = ($lines -join "`r`n")

if ($Check) {
    if (-not (Test-Path $indexPath)) {
        throw "docs/DECISIONS.md does not exist. Run next/tools/Build-DecisionIndex.ps1 to create it."
    }

    $committed = [System.IO.File]::ReadAllText($indexPath)
    if ($committed.TrimEnd() -ne $generated.TrimEnd()) {
        throw "docs/DECISIONS.md is out of date. Run next/tools/Build-DecisionIndex.ps1."
    }

    Write-Output "docs/DECISIONS.md matches $($records.Count) records."
    return
}

[System.IO.File]::WriteAllText($indexPath, $generated, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "docs/DECISIONS.md written from $($records.Count) records."
